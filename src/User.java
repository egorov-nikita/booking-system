/**
 * A person who books rooms.
 * Immutable: there are no setters, so name and email cannot be changed after creation.
 */
public class User {
    private String name;
    private String email;

    public User(String name, String email) {
        this.name = name;
        this.email = email;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }
}